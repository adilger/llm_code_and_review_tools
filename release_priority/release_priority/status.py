"""One status per open change, and whose move it is.

The same rules as the Gerrit Tracker and its public release priorities
page (patch-series-tracker's tracker_status.py), read from Gerrit with
gerrit_cli.ci_parse.  The first rule that applies wins:

    In master-next      queued for landing
    Behind N            an earlier patch in the series has a failure
    Work in progress    marked WIP in Gerrit
    Build failed        Jenkins failed on the patchset CI ran on
    Needs rebase        checkpatch: "cannot be cherry-picked"
    Tests failed        Maloo -1, or enforced failures not being retested
    Janitor failures    failures unique to this patch
    Verified -1         from anyone else
    Reviewer -1         a person voted -1 or -2
    Checkpatch -1       style problems flagged
    Robot -1            a review robot voted -1
    Retest pending      every failing enforced test has a retest requested
    In CI               the build or tests have not finished
    Needs reviewers     fewer people reviewing than it needs
    Comments to answer  short of +1s, unresolved comments, last word not
                        the owner's
    Waiting on review   short of +1s: the reviewers who have not voted
    Ready to land       reviewed, built, Maloo +1
"""

from __future__ import annotations

import re
from datetime import UTC, datetime

from gerrit_cli import ci_parse

GATEKEEPER = {"name": "Gatekeeper", "id": None, "username": ""}
CI = {"name": "CI", "id": None, "username": ""}
CI_BOTS = {ci_parse.JENKINS_BOT, "Jenkins", ci_parse.MALOO_BOT}

# Groups, in the order they are shown: key, title, what it means.
GROUPS = (
    ("review", "Needs review", "built and tested; waiting on reviewers"),
    ("owner", "Needs the owner", "failed tests, a -1, comments or a rebase: the owner has the move"),
    ("ci", "In CI", "building or testing, or a retest has been asked for"),
    ("behind", "Behind another patch", "an earlier patch in its series has to move first"),
    ("ready", "Ready to land", "reviewed, built and tested: waiting on the gatekeeper"),
    ("master_next", "In master-next", "queued for landing on master"),
)
GROUP_KEYS = tuple(k for k, _, _ in GROUPS)
REVIEW_WORDS = ("Waiting on review", "Needs reviewers")


def parse_time(s: str | None) -> datetime | None:
    if not s:
        return None
    return datetime.strptime(s[:19], "%Y-%m-%d %H:%M:%S").replace(tzinfo=UTC)


def person(account: dict) -> dict:
    return {"name": (account.get("name") or account.get("username") or "?").strip(),
            "id": account.get("_account_id"), "username": account.get("username") or ""}


def last_human(detail: dict) -> dict | None:
    """The last message from a person: {name, id, date}.  Gerrit's own
    records of an edit (a hashtag or topic set) are not a person's word."""
    for m in reversed(detail.get("messages") or []):
        a = m.get("author") or {}
        if (m.get("tag") or "").startswith("autogenerated:gerrit:"):
            continue
        if a and not ci_parse.is_bot(a):
            return {"name": a.get("name", ""), "id": a.get("_account_id"), "date": m.get("date", "")}
    return None


def ticket_of(subject: str | None) -> str | None:
    m = re.match(r"\s*(?:DRAFT\s+)?([A-Z][A-Z0-9]*-\d+)", subject or "")
    return m.group(1) if m else None


def normalize(detail: dict, master_next: frozenset | set = frozenset()) -> dict:
    """The fields the rules use, from a Gerrit ChangeInfo with detailed
    labels and accounts, messages and the current revision."""
    owner = person(detail.get("owner") or {})
    cr = {a.get("_account_id"): a.get("value") or 0 for a in
          ((detail.get("labels") or {}).get("Code-Review") or {}).get("all") or []}
    reviewers = []
    for a in (detail.get("reviewers") or {}).get("REVIEWER") or []:
        p = person(a)
        p.update(bot=ci_parse.is_bot(a), review_bot=ci_parse.is_review_bot(a),
                 cr=cr.get(a.get("_account_id"), 0))
        reviewers.append(p)
    tests = ci_parse.parse_tests(detail)
    signals = ci_parse.parse_signals(detail)
    rev = ci_parse.current_revision(detail)
    return {
        "n": int(detail["_number"]),
        "subject": detail.get("subject") or "",
        "branch": detail.get("branch") or "",
        "project": detail.get("project") or "",
        "change_id": detail.get("change_id") or "",
        "owner": owner,
        "uploader": ((rev.get("uploader") or {}).get("name") or "").strip(),
        "ps": ci_parse.current_ps(detail),
        "wip": bool(detail.get("work_in_progress")),
        "build": ci_parse.parse_build(detail)["state"],
        "tests": {"state": tests["state"], "failing": len(tests["failed_tests"]),
                  "retesting": tests["all_failures_retesting"]},
        "unique_failure": signals["unique_failure"],
        "needs_rebase": signals["needs_rebase"],
        "verified_neg": [v["name"] for v in ci_parse.verified_negatives(detail)
                         if v["name"] not in CI_BOTS],
        "reviewers": reviewers,
        "need": 2 if (detail.get("branch") or "master") == "master" else 1,
        "unresolved": detail.get("unresolved_comment_count") or 0,
        "last_human": last_human(detail),
        "updated": detail.get("updated") or "",
        "master_next": detail.get("change_id") in master_next,
        "hashtags": sorted(detail.get("hashtags") or []),
    }


def humans(p: dict) -> list[dict]:
    """The people reviewing p: no bots, not its owner."""
    return [r for r in p["reviewers"] if not r["bot"] and r["id"] != p["owner"]["id"]]


def status(p: dict, behind: int | None = None) -> dict:
    """{tone, words, why, whose: [person], owner_move} for an open change."""
    owner = p["owner"]
    people = humans(p)
    plus = sum(1 for r in people if (r["cr"] or 0) > 0)
    tests = p["tests"]

    def res(tone, words, why, whose):
        return {"tone": tone, "words": words, "why": why, "whose": whose,
                "owner_move": whose == [owner]}

    if p["master_next"]:
        return res("special", "In master-next", "queued for landing", [GATEKEEPER])
    if behind:
        return res("none", f"Behind {behind}",
                   f"an earlier patch in the series ({behind}) has to move first", [])
    if p["wip"]:
        return res("warn", "Work in progress", "marked work in progress in Gerrit", [owner])
    if p["build"] in ("FAILURE", "ABORTED"):
        return res("bad", "Build failed", "the build of the latest patchset failed", [owner])
    if p["needs_rebase"]:
        return res("bad", "Needs rebase", "checkpatch: cannot be cherry-picked", [owner])
    retest = None
    if tests["state"] == "FAIL":
        n = tests["failing"]
        what = f"{n} enforced test{'s' if n != 1 else ''} failing" if n else "Maloo voted -1"
        if not tests["retesting"]:
            return res("bad", "Tests failed", f"{what}, no retest requested", [owner])
        # Waits on CI, unless something below is the owner's to fix anyway.
        retest = res("running", "Retest pending", f"{what}, retest requested", [CI])
    if p["unique_failure"]:
        return res("bad", "Janitor failures", "the janitor found failures unique to this patch",
                   [owner])
    if p["verified_neg"]:
        return res("bad", "Verified -1", "Verified -1 from " + ", ".join(p["verified_neg"]),
                   [owner])
    neg = [r for r in people if (r["cr"] or 0) < 0]
    if neg:
        return res("bad", "Reviewer -1", "-1 from " + ", ".join(r["name"] for r in neg), [owner])
    if any(r["name"] == ci_parse.CHECKPATCH_BOT and (r["cr"] or 0) < 0 for r in p["reviewers"]):
        return res("warn", "Checkpatch -1", "style problems flagged by checkpatch", [owner])
    robots = [r["name"] for r in p["reviewers"] if r["review_bot"] and (r["cr"] or 0) < 0]
    if robots:
        return res("warn", "Robot -1", "-1 from " + ", ".join(robots), [owner])
    if retest:
        return retest
    if p["build"] != "SUCCESS" or tests["state"] != "PASS":
        what = "building" if p["build"] in ("BUILDING", "NONE") else "tests running"
        return res("running", "In CI", f"{what}, no verdict yet", [CI])
    if len(people) < p["need"]:
        return res("warn", "Needs reviewers", f"{len(people)} of {p['need']} reviewers assigned",
                   [owner])
    unresolved = p["unresolved"]
    comments = f"{unresolved} unresolved comment{'s' if unresolved > 1 else ''}"
    if plus < p["need"]:
        last = p["last_human"]
        if unresolved and last and last["id"] != owner["id"]:
            return res("warn", "Comments to answer", f"{comments}, last from {last['name']}",
                       [owner])
        waiting = [r for r in people if not r["cr"]]
        return res("info", "Waiting on review", f"{plus} of {p['need']} +1s", waiting or people)
    return res("good", "Ready to land", f"{plus} +1s, built, Maloo +1"
               + (f"; {comments}" if unresolved else ""), [GATEKEEPER])


def is_hard_blocker(p: dict) -> bool:
    """Holds back the patches after it: its own status is a failure."""
    return status(p)["tone"] == "bad"


def group_of(st: dict) -> str:
    """The page's group for a status."""
    tone, words = st.get("tone"), st.get("words")
    if words == "In master-next":
        return "master_next"
    if tone == "good":
        return "ready"
    if words in REVIEW_WORDS or tone == "info":
        return "review"
    if tone in ("bad", "warn"):
        return "owner"
    if tone == "running":
        return "ci"
    return "behind"
